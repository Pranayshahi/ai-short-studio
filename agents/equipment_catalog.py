"""
Verified equipment catalogue from Wikipedia, for comparison/evolution posters.

Nothing here is generated by a language model: the models come from Wikipedia's
"List of <topic>" tables, and every fact (in-service year, origin country, main gun calibre,
weight, photo) comes from that model's own article infobox. A model without an in-service
year is treated as a prototype/project and never used.
"""

from __future__ import annotations

import re
import time
from typing import Any, Dict, List, Optional, Tuple

import requests

import config

API = "https://en.wikipedia.org/w/api.php"
HEADERS = {"User-Agent": getattr(config, "WIKIMEDIA_USER_AGENT", "AIShortsStudio/2.1 python-requests")}


def _get(params: Dict[str, Any], retries: int = 4) -> Optional[Dict[str, Any]]:
    params = {"format": "json", "formatversion": 2, "maxlag": 5, **params}
    for attempt in range(retries):
        try:
            r = requests.get(API, params=params, headers=HEADERS, timeout=30)
            if r.status_code == 200:
                data = r.json()
                if "error" not in data or data["error"].get("code") != "maxlag":
                    return data
            wait = int(r.headers.get("retry-after") or 0) or (5 * (attempt + 1))
            time.sleep(min(wait, 30))
        except (requests.RequestException, ValueError):
            time.sleep(3 * (attempt + 1))
    return None


# ------------------------------------------------------------------ list page -> candidate titles

def find_list_page(topic: str) -> Optional[str]:
    """'Infantry Combat Vehicles' -> 'List of infantry fighting vehicles'."""
    t = re.sub(r"\s+", " ", topic).strip()
    # Wikipedia's names for common categories ("infantry combat vehicle" -> "infantry fighting vehicle")
    variants = [re.sub(r"\bcombat\b", "fighting", t, flags=re.I), t]
    for v in dict.fromkeys(variants):
        words = [w for w in re.findall(r"[a-z]+", v.lower()) if len(w) > 3]
        ok = lambda title: title.lower().startswith("list of") and words and all(w[:6] in title.lower() for w in words)
        # 1. The exact list title (redirects followed)
        data = _get({"action": "query", "titles": f"List of {v.lower()}", "redirects": 1})
        for pg in (data or {}).get("query", {}).get("pages", []):
            if not pg.get("missing") and ok(pg["title"]):
                return pg["title"]
        # 2. Plain search (ranks the real list first; every topic word must be in the title)
        data = _get({"action": "query", "list": "search", "srsearch": f"List of {v}", "srlimit": 10})
        for hit in (data or {}).get("query", {}).get("search", []):
            if ok(hit["title"]):
                return hit["title"]
    return None


def list_page_models(list_title: str) -> List[Tuple[str, str]]:
    """(article title, section) for every article linked inside the page's tables."""
    data = _get({"action": "parse", "page": list_title, "prop": "wikitext"})
    wt = (data or {}).get("parse", {}).get("wikitext", "")
    wt = re.sub(r"<ref[^>]*/>|<ref[^>]*>.*?</ref>", "", wt, flags=re.S)
    out: List[Tuple[str, str]] = []
    section, in_table = "", 0
    for line in wt.splitlines():
        m = re.match(r"^=+\s*(.*?)\s*=+\s*$", line)
        if m:
            section = m.group(1)
            continue
        if line.startswith("{|"):
            in_table += 1
        elif line.startswith("|}"):
            in_table = max(0, in_table - 1)
        if not in_table:
            continue
        for link in re.findall(r"\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|[^\]]*)?\]\]", line):
            link = link.strip()
            if link and not re.match(r"(?i)(file|image|category|list of|wikt):", link) and not link.lower().startswith("list of") \
                    and (link, section) not in out:
                out.append((link, section))
    return out


# ------------------------------------------------------------------ infobox facts

_YEAR = re.compile(r"\b(19[0-9]{2}|20[0-2][0-9])\b")


def _clean(v: str) -> str:
    v = re.sub(r"<ref[^>]*/>|<ref[^>]*>.*?</ref>", "", v, flags=re.S)
    v = re.sub(r"\{\{(?:flag|flagicon|flagcountry)\|([^}|]+)[^}]*\}\}", r"\1", v, flags=re.I)
    v = re.sub(r"\{\{(?:convert|cvt)\|([\d.,]+)\|([a-zA-Z/]+)[^}]*\}\}", r"\1 \2", v, flags=re.I)  # keeps km/h, m/s
    v = re.sub(r"\{\{[^{}]*\}\}", "", v)
    v = re.sub(r"\[\[(?:[^\]|]*\|)?([^\]]*)\]\]", r"\1", v)
    v = re.sub(r"<br\s*/?>", "; ", v)
    v = re.sub(r"<[^>]+>|'''?", "", v)
    return re.sub(r"\s+", " ", v).strip(" ;,")


def _infobox(wikitext: str) -> Dict[str, str]:
    fields: Dict[str, str] = {}
    # Comments can sit in front of a field on the same line ("<!-- Service history -->| service = ...")
    wikitext = re.sub(r"<!--.*?-->", "\n", wikitext, flags=re.S)
    # field names may contain spaces ("national origin" = "national_origin")
    for m in re.finditer(r"^\s*\|\s*([A-Za-z_0-9][A-Za-z_0-9 -]*?)\s*=\s*(.*?)(?=^\s*\||^\}\}|\Z)", wikitext, flags=re.M | re.S):
        fields[re.sub(r"[ -]+", "_", m.group(1).lower())] = m.group(2).strip()
    return fields


def _service_year(fb: Dict[str, str]) -> Optional[int]:
    for key in ("service", "in_service", "introduced", "introduction", "inservice", "production_date"):
        if fb.get(key):
            m = _YEAR.search(_clean(fb[key])) or _YEAR.search(fb[key])  # {{start date|2015|7|31}}
            if m:
                return int(m.group(1))
    return None


def _calibre_mm(fb: Dict[str, str]) -> Optional[float]:
    # The FIRST gun listed is the vehicle's main armament; later entries are often variants
    text = _clean(fb.get("primary_armament", "") or fb.get("armament", ""))
    for x in re.findall(r"(\d{2,3}(?:\.\d)?)\s*(?:-|\s)?mm", text):
        v = float(x)
        if 12 <= v <= 125:
            return v
    return None


def _weight_t(fb: Dict[str, str]) -> Optional[float]:
    text = _clean(fb.get("weight", ""))
    m = re.search(r"(\d{1,3}(?:\.\d{1,2})?)\s*(?:t|tonnes?|tons?|metric tons?)\b", text, flags=re.I)
    val = float(m.group(1)) if m else None
    if val is None:
        m = re.search(r"([\d,]{4,7})\s*kg", text)
        val = round(float(m.group(1).replace(",", "")) / 1000, 1) if m else None
    return val if val and 3 <= val <= 80 else None


_NATIONALITIES = {
    "american": "United States", "u.s.": "United States", "us": "United States", "russian": "Russia", "soviet": "Russia",
    "british": "United Kingdom", "french": "France", "german": "Germany", "chinese": "China", "israeli": "Israel",
    "indian": "India", "ukrainian": "Ukraine", "turkish": "Turkey", "iranian": "Iran", "italian": "Italy",
    "swedish": "Sweden", "norwegian": "Norway", "japanese": "Japan", "south korean": "South Korea",
    "taiwanese": "Taiwan", "pakistani": "Pakistan", "brazilian": "Brazil", "spanish": "Spain", "polish": "Poland",
    "european": "", "anglo-french": "United Kingdom", "franco-british": "France",
}


def _nationality(lead: str) -> str:
    """'The BGM-109G Gryphon ... is a ... American ...' -> 'United States' (when the infobox has no origin)."""
    m = re.search(r"\b(?:is|was) an? ([^.]{0,120})", lead or "", re.I)
    text = (m.group(1) if m else (lead or "")[:160]).lower()
    for adj in sorted(_NATIONALITIES, key=len, reverse=True):
        if re.search(rf"(?<![a-z]){re.escape(adj)}(?![a-z])", text) and _NATIONALITIES[adj]:
            return _NATIONALITIES[adj]
    # "... developed by the United States Air Force" / "... built in Russia"
    full = (lead or "")[:400]
    m = re.search(r"\b(?:developed|designed|built|manufactured|produced|made|fielded)\b[^.]{0,40}?\b(?:by|in) (?:the )?"
                  r"(United States|United Kingdom|Soviet Union|Russia|France|Germany|China|Israel|India|Ukraine|Turkey|"
                  r"Iran|Italy|Sweden|Norway|Japan|South Korea|Taiwan|Pakistan|Brazil|Spain|Poland)", full)
    if m:
        return "Russia" if m.group(1) == "Soviet Union" else m.group(1)
    return ""


# Infobox fields worth a WeaponX bullet, in order of preference (label shown on the chart)
_SPEC_FIELDS = [
    ("range", "Range"), ("vehicle_range", "Range"), ("max_range", "Range"), ("effective_range", "Range"),
    ("speed", "Speed"), ("max_speed", "Speed"), ("warhead", "Warhead"), ("warhead_weight", "Warhead"),
    ("number", "No. built"), ("number_built", "No. built"), ("produced", "No. built"),
    ("guidance", "Guidance"), ("engine", "Engine"), ("propellant", "Propellant"), ("cartridge", "Cartridge"),
    ("calibre", "Calibre"), ("caliber", "Calibre"), ("rate", "Fire rate"), ("weight", "Weight"), ("length", "Length"),
]


_UNIT = r"(?:km/h|km|m/s|mph|nmi|mi|kg|lb|mm|cm|m|t|tonnes?|kN|rounds/min|rpm|kt)"
_VALUE = re.compile(rf"((?:>|<|≈|~|at least |up to |over )?\d[\d,.]*(?:\s*[–-]\s*\d[\d,.]*)?\s*{_UNIT}\b|mach\s*\d+(?:\.\d+)?(?:\s*[–-]\s*\d+(?:\.\d+)?)?)", re.I)


def _specs(fb: Dict[str, str]) -> Dict[str, str]:
    """Clean 'Label - value' specs: only a number with a unit (or Mach / a plain count for No. built)."""
    import html
    out: Dict[str, str] = {}
    for key, label in _SPEC_FIELDS:
        if label in out or not fb.get(key):
            continue
        v = html.unescape(_clean(fb[key])).replace("\xa0", " ")
        if re.search(r"\bvar(y|ies|iable)\b|classified|unknown", v, re.I):
            continue
        if label == "No. built":
            m = re.search(r"\b(\d{1,3}(?:,\d{3})+|\d{2,7})\b", v)
            val = m.group(1) if m else ""
        elif label in ("Engine", "Guidance", "Propellant", "Cartridge"):
            val = re.split(r";|\(|,", v)[0].strip()
            val = val if 3 <= len(val) <= 32 else ""
        else:
            m = _VALUE.search(v)
            val = re.sub(r"\s+", " ", m.group(1)).strip() if m else ""
            val = re.sub(r"(?i)^mach", "Mach", val)
        if val:
            out[label] = val
    return out


def _origin(fb: Dict[str, str]) -> str:
    o = _clean(fb.get("origin", "") or fb.get("place-of-origin", "") or fb.get("place_of_origin", "")
               or fb.get("national_origin", ""))  # aircraft infoboxes
    return re.split(r";|,|/| and ", o)[0].strip()


def fetch_models(titles: List[str], thumb: int = 640) -> Dict[str, Dict[str, Any]]:
    """Infobox facts + lead photo for each title (batched 50 per request, redirects followed)."""
    out: Dict[str, Dict[str, Any]] = {}
    for i in range(0, len(titles), 50):
        batch = titles[i:i + 50]
        data = _get({"action": "query", "titles": "|".join(batch), "redirects": 1, "prop": "revisions|pageimages|info",
                     "rvprop": "content", "rvslots": "main", "rvsection": 0, "piprop": "thumbnail|name",
                     "pithumbsize": thumb, "pilimit": 50})
        if not data:
            continue
        q = data.get("query", {})
        back = {r["to"]: r["from"] for r in q.get("redirects", [])}
        for pg in q.get("pages", []):
            if pg.get("missing"):
                continue
            wt = (pg.get("revisions") or [{}])[0].get("slots", {}).get("main", {}).get("content", "")
            fb = _infobox(wt)
            year = _service_year(fb)
            # Opening sentence (after the infobox) as a fallback description of what the article is about
            # (templates removed twice to drop nested ones; the lead starts at the bolded article name)
            lead = re.sub(r"\{\{[^{}]*\}\}", "", re.sub(r"\{\{[^{}]*\}\}", "", wt))
            m_bold = re.search(r"[^\n]*'''[^'\n]+'''", lead)
            lead = _clean(lead[m_bold.start():m_bold.start() + 600]) if m_bold else ""
            status = _clean(fb.get("status", "")).lower()
            origin = _origin(fb) or _nationality(lead)
            out[pg["title"]] = {
                "title": pg["title"],
                "requested_as": back.get(pg["title"], pg["title"]),
                "name": _clean(fb.get("name", "")) or pg["title"],
                "year": year,
                "origin": origin,
                "specs": _specs(fb),
                "calibre_mm": _calibre_mm(fb),
                "weight_t": _weight_t(fb),
                "type": _clean(fb.get("type", "") or fb.get("aircraft_type", "")),  # aircraft: aircraft_type
                "lead": lead[:300],
                "article_length": pg.get("length", 0),
                "is_prototype": (year is None) or any(w in status for w in ("prototype", "cancel", "development")),
                "image_url": (pg.get("thumbnail") or {}).get("source"),
                "image_file": pg.get("pageimage"),
                "url": f"https://en.wikipedia.org/wiki/{pg['title'].replace(' ', '_')}",
            }
        time.sleep(1.0)  # polite pacing (Wikimedia robot policy)
    return out


# ------------------------------------------------------------------ pairing

_ORIGIN_ALIASES = {"soviet union": "Russia", "ussr": "Russia", "russian federation": "Russia",
                   "west germany": "Germany", "federal republic of germany": "Germany",
                   "united states of america": "United States", "usa": "United States",
                   "republic of korea": "South Korea", "korea": "South Korea",
                   "people's republic of china": "China", "prc": "China"}


def _country(origin: str) -> str:
    o = origin.strip()
    return _ORIGIN_ALIASES.get(o.lower(), o)


def _label(old: Dict[str, Any], new: Dict[str, Any]) -> str:
    if old.get("calibre_mm") and new.get("calibre_mm"):
        f = lambda x: f"{x:g} mm"
        return f"Main gun {f(old['calibre_mm'])} → {f(new['calibre_mm'])}" if old["calibre_mm"] != new["calibre_mm"] else f"Main gun {f(new['calibre_mm'])}"
    if old.get("weight_t") and new.get("weight_t"):
        return f"Weight {old['weight_t']:g} t → {new['weight_t']:g} t"
    return f"{new['year'] - old['year']} years of development"


def matches_type(model: Dict[str, Any], type_phrase: str) -> bool:
    """Infobox type matches the topic (e.g. 'Infantry fighting vehicle'), so armies, guns, trucks
    and personnel carriers linked from the list page are left out."""
    words = [w[:6] for w in re.findall(r"[a-z]+", type_phrase.lower()) if len(w) > 3 and w not in ("vehicles", "vehicle", "system", "systems")]
    t = (model.get("type") or "").lower()
    if not t:
        # Empty infobox type (e.g. BMP-1): use the article's opening sentence instead
        t = (model.get("lead") or "").lower()[:200]
    return bool(words) and all(w in t for w in words)


def build_pairs(models: Dict[str, Dict[str, Any]], min_gap: int = 10, max_rows: int = 8, type_phrase: str = "",
                sections: Optional[Dict[str, str]] = None, min_rows: int = 6) -> List[Dict[str, Any]]:
    """
    1. Same-country historical -> modern pairs (oldest well-documented model -> newest).
    2. If fewer than min_rows, comparable counterparts: remaining older and newer models of the same
       kind (e.g. tracked with tracked, from the list page's sections), labelled with both countries.
    """
    sections = sections or {}
    usable = [m for m in models.values() if not m["is_prototype"] and m["year"] and m["year"] <= 2026 and m["origin"] and m["image_url"]
              and (not type_phrase or matches_type(m, type_phrase))]
    # Collapse redirect duplicates and keep well-documented articles first
    seen, uniq = set(), []
    for m in sorted(usable, key=lambda x: -x.get("article_length", 0)):
        if m["title"] not in seen:
            seen.add(m["title"])
            uniq.append(m)
    by_country: Dict[str, List[Dict[str, Any]]] = {}
    for m in uniq:
        by_country.setdefault(_country(m["origin"]), []).append(m)

    def notable(ms):
        # Well-documented models only (at least half the length of the group's best-known article),
        # so an obscure variant doesn't stand for a country's history
        top = max(x.get("article_length", 0) for x in ms)
        return [x for x in ms if x.get("article_length", 0) >= top * 0.5] or ms

    pairs: List[Dict[str, Any]] = []
    used = set()
    for country, ms in sorted(by_country.items(), key=lambda kv: -len(kv[1])):
        cand = notable(ms)
        old = min(cand, key=lambda x: x["year"])
        new = max(ms, key=lambda x: x["year"])
        if new["year"] - old["year"] >= min_gap and old["title"] != new["title"]:
            pairs.append({"country": country, "historical": old, "modern": new, "label": _label(old, new), "kind": "successor"})
            used.update({old["title"], new["title"]})
        if len(pairs) >= max_rows:
            break

    if len(pairs) < min_rows:
        def kind(m):
            sec = sections.get(m["requested_as"], sections.get(m["title"], "")).lower()
            if "wheel" in sec:
                return "wheeled"
            if "track" in sec:
                return "tracked"
            text = f"{m.get('type', '')} {m.get('lead', '')}".lower()
            return "wheeled" if re.search(r"wheel|\b[468]\s*[x×]\s*[468]\b", text) else "tracked"
        rest = [m for m in uniq if m["title"] not in used]
        for k in ("tracked", "wheeled"):
            pool = sorted([m for m in rest if kind(m) == k], key=lambda x: x["year"])
            olds = [m for m in pool if m["year"] < 1995]
            news = [m for m in reversed(pool) if m["year"] >= 2005]
            for old, new in zip(sorted(olds, key=lambda x: -x.get("article_length", 0)), news):
                if len(pairs) >= max_rows:
                    break
                if new["year"] - old["year"] >= min_gap:
                    pairs.append({"country": f"{_country(old['origin'])} → {_country(new['origin'])}", "historical": old, "modern": new,
                                  "label": _label(old, new), "kind": "counterpart"})
                    used.update({old["title"], new["title"]})
    pairs.sort(key=lambda p: p["historical"]["year"])
    return pairs[:max_rows]
